package com.tourism.dao;

import com.tourism.config.DBConnection;
import com.tourism.model.Booking;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * Data Access Object for the bookings table. Only this class talks to the database
 * for bookings. Every query uses PreparedStatement with '?' (prevents SQL injection).
 * Concepts: JDBC, exception handling, try-with-resources, collections (ArrayList), generics.
 */
public class BookingDAO {

    // Same SELECT is reused by getBookingById() and getUserBookings()
    private static final String SELECT_BOOKING =
            "SELECT b.booking_id, b.user_id, b.package_id, p.title, b.travel_date, "
          + "b.number_of_guests, b.total_cost, b.booking_status, b.refund_amount, b.booking_date "
          + "FROM bookings b JOIN travel_packages p ON b.package_id = p.package_id ";

    /**
     * Saves a new booking inside a transaction.
     * Step 1: check the package is still active. Step 2: insert the booking.
     * If anything fails, rollback() undoes everything, otherwise commit() saves it.
     *
     * @return the new booking_id generated by MySQL
     */
    public int createBooking(Booking booking) throws SQLException {
        String checkSql = "SELECT is_active FROM travel_packages WHERE package_id = ?";
        String insertSql = "INSERT INTO bookings (user_id, package_id, travel_date, "
                + "number_of_guests, total_cost, booking_status) VALUES (?, ?, ?, ?, ?, ?)";

        // DBConnection is a Singleton, so we must NOT close this connection ourselves.
        Connection conn = DBConnection.getInstance().getConnection();
        boolean oldAutoCommit = conn.getAutoCommit();

        try {
            conn.setAutoCommit(false);                       // start transaction

            try (PreparedStatement check = conn.prepareStatement(checkSql)) {
                check.setInt(1, booking.getPackageId());
                try (ResultSet rs = check.executeQuery()) {
                    if (!rs.next() || !rs.getBoolean("is_active")) {
                        throw new SQLException("This package is no longer available.");
                    }
                }
            }

            int newId;
            try (PreparedStatement insert = conn.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)) {
                insert.setInt(1, booking.getUserId());
                insert.setInt(2, booking.getPackageId());
                insert.setDate(3, java.sql.Date.valueOf(booking.getTravelDate()));
                insert.setInt(4, booking.getNumberOfGuests());
                insert.setDouble(5, booking.getTotalCost());
                insert.setString(6, Booking.CONFIRMED);
                insert.executeUpdate();

                try (ResultSet keys = insert.getGeneratedKeys()) {
                    if (!keys.next()) {
                        throw new SQLException("Booking could not be saved.");
                    }
                    newId = keys.getInt(1);
                }
            }

            conn.commit();                                   // all steps worked
            return newId;

        } catch (SQLException e) {
            conn.rollback();                                 // something failed, undo
            throw e;
        } finally {
            conn.setAutoCommit(oldAutoCommit);               // put the connection back as it was
        }
    }

    /**
     * Marks a CONFIRMED booking as CANCELLED and stores the refund amount.
     *
     * @return true if a booking was updated, false if it was not found / not confirmed
     */
    public boolean cancelBooking(int bookingId, double refundAmount) throws SQLException {
        String sql = "UPDATE bookings SET booking_status = ?, refund_amount = ?, payment_status = ? "
                   + "WHERE booking_id = ? AND booking_status = ?";
        Connection conn = DBConnection.getInstance().getConnection();

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, Booking.CANCELLED);
            ps.setDouble(2, refundAmount);
            ps.setString(3, refundAmount > 0 ? "REFUNDED" : "CANCELLED_NO_REFUND");
            ps.setInt(4, bookingId);
            ps.setString(5, Booking.CONFIRMED);
            return ps.executeUpdate() == 1;
        }
    }

    /** Returns all bookings of one user, newest first. */
    public List<Booking> getUserBookings(int userId) throws SQLException {
        String sql = SELECT_BOOKING + "WHERE b.user_id = ? ORDER BY b.booking_date DESC";
        Connection conn = DBConnection.getInstance().getConnection();
        List<Booking> bookings = new ArrayList<>();

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, userId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    bookings.add(mapRow(rs));
                }
            }
        }
        return bookings;
    }

    /** Returns one booking, or null if the id does not exist. */
    public Booking getBookingById(int bookingId) throws SQLException {
        String sql = SELECT_BOOKING + "WHERE b.booking_id = ?";
        Connection conn = DBConnection.getInstance().getConnection();

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, bookingId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapRow(rs) : null;
            }
        }
    }

    /** CONFIRMED bookings whose travel date is already over become COMPLETED (needed for reviews). */
    public int markPastTripsCompleted() throws SQLException {
        String sql = "UPDATE bookings SET booking_status = ? WHERE booking_status = ? AND travel_date < ?";
        Connection conn = DBConnection.getInstance().getConnection();

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, Booking.COMPLETED);
            ps.setString(2, Booking.CONFIRMED);
            ps.setDate(3, java.sql.Date.valueOf(LocalDate.now()));
            return ps.executeUpdate();
        }
    }

    /** Returns all bookings for the administrator, optionally filtered by status. */
    public List<Booking> findAllForAdmin(String status) throws SQLException {
        String normalized = status == null ? "ALL" : status.trim().toUpperCase();
        String sql = SELECT_BOOKING + ("ALL".equals(normalized) ? "" : "WHERE b.booking_status = ? ")
                + "ORDER BY b.booking_date DESC";
        Connection conn = DBConnection.getInstance().getConnection();
        if (conn == null) throw new SQLException("Database connection is unavailable.");
        List<Booking> bookings = new ArrayList<>();
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            if (!"ALL".equals(normalized)) ps.setString(1, normalized);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) bookings.add(mapRow(rs));
            }
        }
        return bookings;
    }

    // Converts the current row of the ResultSet into a Booking object
    private Booking mapRow(ResultSet rs) throws SQLException {
        Booking b = new Booking();
        b.setBookingId(rs.getInt("booking_id"));
        b.setUserId(rs.getInt("user_id"));
        b.setPackageId(rs.getInt("package_id"));
        b.setPackageTitle(rs.getString("title"));
        b.setTravelDate(rs.getDate("travel_date").toLocalDate());
        b.setNumberOfGuests(rs.getInt("number_of_guests"));
        b.setTotalCost(rs.getDouble("total_cost"));
        b.setStatus(rs.getString("booking_status"));
        b.setRefundAmount(rs.getDouble("refund_amount"));
        b.setBookingDate(rs.getTimestamp("booking_date").toLocalDateTime());
        return b;
    }
}
